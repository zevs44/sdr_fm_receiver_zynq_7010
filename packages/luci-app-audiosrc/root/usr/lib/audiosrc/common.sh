# /usr/lib/audiosrc/common.sh
# Общая логика поверх audiosrc (/usr/sbin/audiosrc, отдельный пакет) для
# luci-app-audiosrc. Используется и rpcd-бэкендом (luci.audiosrc), и
# /etc/init.d/audiosrc.
#
# Адрес регистра зашит в сам audiosrc через #define (AUDIOSRC_REG_ADDR в
# audiosrc.c), а не передаётся аргументом - здесь его больше нет, поэтому
# и держать его в UCI (audiosrc.settings.reg_base) смысла не было: значение
# оттуда всё равно ни на что не влияло бы.

# Единственное место, где имя источника связано со значением регистра
# i2s_axi_mux_top (NUM_INPUTS=3, SEL_WIDTH=2): 0=Radio, 1=myMPD, 2=Bluetooth
idx_for() {
	case "$1" in
		radio)     echo 0 ;;
		mympd)     echo 1 ;;
		bluetooth) echo 2 ;;
		*)         echo "" ;;
	esac
}

name_for() {
	case "$1" in
		0) echo radio ;;
		1) echo mympd ;;
		2) echo bluetooth ;;
		*) echo "" ;;
	esac
}

# $1 - индекс канала (0/1/2), должен быть уже провалидирован вызывающим кодом
# через idx_for(). audiosrc сам проверяет запись обратным чтением и
# возвращает ненулевой код, если она не подтвердилась. Путь абсолютный:
# скрипт вызывается из rpcd и из init.d на раннем этапе загрузки, полагаться
# на содержимое PATH в этих контекстах не стоит.
write_reg() {
	/usr/sbin/audiosrc "$1" >/dev/null
}

# Читает регистр напрямую, без аргумента - у audiosrc это режим чтения.
# Возвращает то, что он печатает: "0x%08X" (например "0x00000002"), либо
# пусто/ошибку, если чтение не удалось. Нужно затем, чтобы узнать РЕАЛЬНОЕ
# состояние железа, а не то, что последним записал сам плагин - регистр
# можно поменять и в обход него (devmem2, другой инструмент).
read_reg() {
	/usr/sbin/audiosrc
}
